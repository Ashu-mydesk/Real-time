USE ROLE ACCOUNTADMIN;
USE DATABASE MYDESK;
USE SCHEMA PUBLIC;

---------------------------------------------------------------------------
-- 1. Pre_Stage Tables (Direct 1:1 landing from S3 files)
---------------------------------------------------------------------------
CREATE OR REPLACE TABLE PRE_STAGE_LINEITEM LIKE SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;
CREATE OR REPLACE TABLE PRE_STAGE_PART     LIKE SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART;
CREATE OR REPLACE TABLE PRE_STAGE_SUPPLIER LIKE SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER;

-- Dim Date Structure (TPC-H SF1 Date representation or custom calendar)
CREATE OR REPLACE TABLE PRE_STAGE_DIM_DATE (
    DATE_KEY       DATE,
    YEAR           NUMBER,
    QUARTER        NUMBER,
    MONTH          NUMBER,
    DAY_OF_MONTH   NUMBER,
    DAY_NAME       VARCHAR(20),
    MONTH_NAME     VARCHAR(20)
);

---------------------------------------------------------------------------
-- 2. Stage Tables (Flush & Fill + INSERT_GMT_TIMESTAMP)
---------------------------------------------------------------------------
CREATE OR REPLACE TABLE STAGE_LINEITEM AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS INSERT_GMT_TIMESTAMP 
FROM PRE_STAGE_LINEITEM WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_PART AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS INSERT_GMT_TIMESTAMP 
FROM PRE_STAGE_PART WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_SUPPLIER AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS INSERT_GMT_TIMESTAMP 
FROM PRE_STAGE_SUPPLIER WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_DIM_DATE AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS INSERT_GMT_TIMESTAMP 
FROM PRE_STAGE_DIM_DATE WHERE 1=0;

---------------------------------------------------------------------------
-- 3. Stage_Derived Tables (Flush & Fill + UPDATE_GMT_TIMESTAMP + Transformations)
---------------------------------------------------------------------------
CREATE OR REPLACE TABLE STAGE_LINEITEM_DERIVED AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS UPDATE_GMT_TIMESTAMP 
FROM STAGE_LINEITEM WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_PART_DERIVED AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS UPDATE_GMT_TIMESTAMP 
FROM STAGE_PART WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_SUPPLIER_DERIVED AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS UPDATE_GMT_TIMESTAMP 
FROM STAGE_SUPPLIER WHERE 1=0;

CREATE OR REPLACE TABLE STAGE_DIM_DATE_DERIVED AS 
SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS UPDATE_GMT_TIMESTAMP 
FROM STAGE_DIM_DATE WHERE 1=0;

---------------------------------------------------------------------------
-- 4. Final Joined Fact Target Table
---------------------------------------------------------------------------
CREATE OR REPLACE TABLE FACT_LINEITEM_ANALYTICS (
    -- Order / Line Details
    L_ORDERKEY              NUMBER,
    L_LINENUMBER            NUMBER,
    L_QUANTITY              NUMBER(12, 2),
    L_EXTENDEDPRICE         NUMBER(12, 2),
    L_DISCOUNT              NUMBER(12, 2),
    L_TAX                   NUMBER(12, 2),
    L_RETURNFLAG            VARCHAR(1),
    L_LINESTATUS            VARCHAR(1),
    L_SHIPDATE              DATE,
    
    -- Part Dimensions (Joined on L_PARTKEY = P_PARTKEY)
    P_PARTKEY               NUMBER,
    P_NAME                  VARCHAR(55),
    P_MFGR                  VARCHAR(25),
    P_BRAND                 VARCHAR(10),
    P_TYPE                  VARCHAR(25),
    P_SIZE                  NUMBER,
    P_RETAILPRICE           NUMBER(12, 2),

    -- Supplier Dimensions (Joined on L_SUPPKEY = S_SUPPKEY)
    S_SUPPKEY               NUMBER,
    S_NAME                  VARCHAR(25),
    S_ADDRESS               VARCHAR(40),
    S_NATIONKEY             NUMBER,
    S_PHONE                 VARCHAR(15),
    S_ACCTBAL               NUMBER(12, 2),

    -- Date Dimensions (Joined on L_SHIPDATE = DATE_KEY)
    SHIP_YEAR               NUMBER,
    SHIP_QUARTER            NUMBER,
    SHIP_MONTH              NUMBER,
    SHIP_DAY_NAME           VARCHAR(20),

    -- Audit Timestamps
    INSERT_GMT_TIMESTAMP    TIMESTAMP_NTZ,
    UPDATE_GMT_TIMESTAMP    TIMESTAMP_NTZ,
    FINAL_LOAD_GMT          TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ
);




CREATE OR REPLACE PROCEDURE MYDESK.PUBLIC.SP_UNLOAD_4_TABLES_TO_S3()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
DECLARE
    V_TS VARCHAR;
    V_SQL VARCHAR;
BEGIN
    V_TS := TO_CHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHH24MISS');

    -- 1. Unload LINEITEM
    V_SQL := 'COPY INTO @MYDESK.PUBLIC.STAGE_TABLE_S3/Fact_lineitem_' || V_TS || '.txt ' ||
             'FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM ' ||
             'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) ' ||
             'HEADER = TRUE SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;';
    EXECUTE IMMEDIATE :V_SQL;

    -- 2. Unload PART
    V_SQL := 'COPY INTO @MYDESK.PUBLIC.STAGE_TABLE_S3/Dim_part_' || V_TS || '.txt ' ||
             'FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART ' ||
             'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) ' ||
             'HEADER = TRUE SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;';
    EXECUTE IMMEDIATE :V_SQL;

    -- 3. Unload SUPPLIER
    V_SQL := 'COPY INTO @MYDESK.PUBLIC.STAGE_TABLE_S3/Dim_supplier_' || V_TS || '.txt ' ||
             'FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER ' ||
             'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) ' ||
             'HEADER = TRUE SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;';
    EXECUTE IMMEDIATE :V_SQL;

    -- 4. Unload DIM_DATE (Generating dates from TPCH order calendar)
    V_SQL := 'COPY INTO @MYDESK.PUBLIC.STAGE_TABLE_S3/Dim_date_' || V_TS || '.txt ' ||
             'FROM ( ' ||
             '  SELECT DISTINCT ' ||
             '    O_ORDERDATE AS DATE_KEY, ' ||
             '    EXTRACT(YEAR FROM O_ORDERDATE) AS YEAR, ' ||
             '    EXTRACT(QUARTER FROM O_ORDERDATE) AS QUARTER, ' ||
             '    EXTRACT(MONTH FROM O_ORDERDATE) AS MONTH, ' ||
             '    EXTRACT(DAY FROM O_ORDERDATE) AS DAY_OF_MONTH, ' ||
             '    DAYNAME(O_ORDERDATE) AS DAY_NAME, ' ||
             '    MONTHNAME(O_ORDERDATE) AS MONTH_NAME ' ||
             '  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS ' ||
             ') ' ||
             'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) ' ||
             'HEADER = TRUE SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;';
    EXECUTE IMMEDIATE :V_SQL;

    RETURN 'Successfully unloaded all 4 tables with timestamp suffix: ' || V_TS;
EXCEPTION
    WHEN OTHER THEN
        RETURN 'Export failed: ' || :SQLERRM;
END;


CREATE OR REPLACE PROCEDURE MYDESK.PUBLIC.SP_EXECUTE_FULL_ETL_PIPELINE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
DECLARE
    V_ARCHIVE_TS VARCHAR;
    V_SQL_ARCHIVE VARCHAR;
    V_FINAL_ROWS  NUMBER := 0;
BEGIN
    V_ARCHIVE_TS := TO_CHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHH24MISS');

    ---------------------------------------------------------------------------
    -- STEP 1: INGESTION INTO PRE_STAGE (FROM S3 FILES)
    ---------------------------------------------------------------------------
    TRUNCATE TABLE MYDESK.PUBLIC.PRE_STAGE_LINEITEM;
    TRUNCATE TABLE MYDESK.PUBLIC.PRE_STAGE_PART;
    TRUNCATE TABLE MYDESK.PUBLIC.PRE_STAGE_SUPPLIER;
    TRUNCATE TABLE MYDESK.PUBLIC.PRE_STAGE_DIM_DATE;

    COPY INTO MYDESK.PUBLIC.PRE_STAGE_LINEITEM
    FROM @MYDESK.PUBLIC.STAGE_TABLE_S3
    PATTERN = '.*[Ff]act_lineitem_.*[.]txt'
    FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 EMPTY_FIELD_AS_NULL = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE)
    FORCE = TRUE;

    COPY INTO MYDESK.PUBLIC.PRE_STAGE_PART
    FROM @MYDESK.PUBLIC.STAGE_TABLE_S3
    PATTERN = '.*[Dd]im_part_.*[.]txt'
    FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 EMPTY_FIELD_AS_NULL = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE)
    FORCE = TRUE;

    COPY INTO MYDESK.PUBLIC.PRE_STAGE_SUPPLIER
    FROM @MYDESK.PUBLIC.STAGE_TABLE_S3
    PATTERN = '.*[Dd]im_supplier_.*[.]txt'
    FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 EMPTY_FIELD_AS_NULL = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE)
    FORCE = TRUE;

    COPY INTO MYDESK.PUBLIC.PRE_STAGE_DIM_DATE
    FROM @MYDESK.PUBLIC.STAGE_TABLE_S3
    PATTERN = '.*[Dd]im_date_.*[.]txt'
    FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 EMPTY_FIELD_AS_NULL = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE)
    FORCE = TRUE;

    ---------------------------------------------------------------------------
    -- STEP 2: FLUSH & FILL INTO STAGE (+ INSERT_GMT_TIMESTAMP)
    ---------------------------------------------------------------------------
    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_LINEITEM;
    INSERT INTO MYDESK.PUBLIC.STAGE_LINEITEM
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.PRE_STAGE_LINEITEM;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_PART;
    INSERT INTO MYDESK.PUBLIC.STAGE_PART
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.PRE_STAGE_PART;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_SUPPLIER;
    INSERT INTO MYDESK.PUBLIC.STAGE_SUPPLIER
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.PRE_STAGE_SUPPLIER;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_DIM_DATE;
    INSERT INTO MYDESK.PUBLIC.STAGE_DIM_DATE
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.PRE_STAGE_DIM_DATE;

    ---------------------------------------------------------------------------
    -- STEP 3: FLUSH & FILL INTO STAGE_DERIVED (+ UPDATE_GMT_TIMESTAMP & TRANSFORMS)
    ---------------------------------------------------------------------------
    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_LINEITEM_DERIVED;
    INSERT INTO MYDESK.PUBLIC.STAGE_LINEITEM_DERIVED
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.STAGE_LINEITEM;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_PART_DERIVED;
    INSERT INTO MYDESK.PUBLIC.STAGE_PART_DERIVED
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.STAGE_PART;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_SUPPLIER_DERIVED;
    INSERT INTO MYDESK.PUBLIC.STAGE_SUPPLIER_DERIVED
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.STAGE_SUPPLIER;

    TRUNCATE TABLE MYDESK.PUBLIC.STAGE_DIM_DATE_DERIVED;
    INSERT INTO MYDESK.PUBLIC.STAGE_DIM_DATE_DERIVED
    SELECT *, CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ FROM MYDESK.PUBLIC.STAGE_DIM_DATE;

    ---------------------------------------------------------------------------
    -- STEP 4: DELETE / INSERT (4-TABLE JOIN INTO FINAL TARGET)
    ---------------------------------------------------------------------------
    INSERT OVERWRITE INTO MYDESK.PUBLIC.FACT_LINEITEM_ANALYTICS (
        L_ORDERKEY,
        L_LINENUMBER,
        L_QUANTITY,
        L_EXTENDEDPRICE,
        L_DISCOUNT,
        L_TAX,
        L_RETURNFLAG,
        L_LINESTATUS,
        L_SHIPDATE,
        P_PARTKEY,
        P_NAME,
        P_MFGR,
        P_BRAND,
        P_TYPE,
        P_SIZE,
        P_RETAILPRICE,
        S_SUPPKEY,
        S_NAME,
        S_ADDRESS,
        S_NATIONKEY,
        S_PHONE,
        S_ACCTBAL,
        SHIP_YEAR,
        SHIP_QUARTER,
        SHIP_MONTH,
        SHIP_DAY_NAME,
        INSERT_GMT_TIMESTAMP,
        UPDATE_GMT_TIMESTAMP,
        FINAL_LOAD_GMT
    )
    SELECT 
        l.L_ORDERKEY,
        l.L_LINENUMBER,
        l.L_QUANTITY,
        l.L_EXTENDEDPRICE,
        l.L_DISCOUNT,
        l.L_TAX,
        l.L_RETURNFLAG,
        l.L_LINESTATUS,
        l.L_SHIPDATE,
        
        -- Join 1: PART (L_PARTKEY = P_PARTKEY)
        p.P_PARTKEY,
        p.P_NAME,
        p.P_MFGR,
        p.P_BRAND,
        p.P_TYPE,
        p.P_SIZE,
        p.P_RETAILPRICE,

        -- Join 2: SUPPLIER (L_SUPPKEY = S_SUPPKEY)
        s.S_SUPPKEY,
        s.S_NAME,
        s.S_ADDRESS,
        s.S_NATIONKEY,
        s.S_PHONE,
        s.S_ACCTBAL,

        -- Join 3: DIM_DATE (L_SHIPDATE = DATE_KEY)
        d.YEAR,
        d.QUARTER,
        d.MONTH,
        d.DAY_NAME,

        l.INSERT_GMT_TIMESTAMP,
        l.UPDATE_GMT_TIMESTAMP,
        CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ
    FROM MYDESK.PUBLIC.STAGE_LINEITEM_DERIVED l
    INNER JOIN MYDESK.PUBLIC.STAGE_PART_DERIVED p
        ON l.L_PARTKEY = p.P_PARTKEY
    INNER JOIN MYDESK.PUBLIC.STAGE_SUPPLIER_DERIVED s
        ON l.L_SUPPKEY = s.S_SUPPKEY
    LEFT JOIN MYDESK.PUBLIC.STAGE_DIM_DATE_DERIVED d
        ON l.L_SHIPDATE = d.DATE_KEY;

    SELECT COUNT(*) INTO :V_FINAL_ROWS FROM MYDESK.PUBLIC.FACT_LINEITEM_ANALYTICS;

    ---------------------------------------------------------------------------
    -- STEP 5: ARCHIVE TO AWS (ARCHIVE FOLDER WITH TIMESTAMP PREFIX)
    ---------------------------------------------------------------------------
    V_SQL_ARCHIVE := 'COPY INTO @MYDESK.PUBLIC.STAGE_TABLE_S3/archive/Fact_lineitem_' || V_ARCHIVE_TS || '.txt ' ||
                     'FROM MYDESK.PUBLIC.FACT_LINEITEM_ANALYTICS ' ||
                     'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) ' ||
                     'HEADER = TRUE SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;';
    EXECUTE IMMEDIATE :V_SQL_ARCHIVE;

    RETURN 'ETL run succeeded. Total joined records loaded into Fact: ' || :V_FINAL_ROWS || '. Archived snapshot created.';

EXCEPTION
    WHEN OTHER THEN
        RETURN 'Pipeline failed: ' || :SQLERRM;
END;


CALL MYDESK.PUBLIC.SP_UNLOAD_4_TABLES_TO_S3();


CALL MYDESK.PUBLIC.SP_EXECUTE_FULL_ETL_PIPELINE();


